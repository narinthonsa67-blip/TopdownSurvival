using UnityEngine; // นำเข้าไลบรารีหลักของ Unity เพื่อใช้งานฟังก์ชันและคอมโพเนนต์พื้นฐาน
public class AmmoBoxPickup : MonoBehaviour // ประกาศคลาสชื่อ AmmoBoxPickup สืบทอดจาก MonoBehaviour เพื่อจัดการการเก็บกล่องกระสุน
{ // เปิดขอบเขตการทำงานของคลาส AmmoBoxPickup
    [Header("Ammo Amount")] // แสดงหัวข้อหมวดหมู่ "Ammo Amount" บนหน้าต่าง Inspector ใน Unity
    public int ammoAmount = 15; // จำนวนกระสุนที่ได้ต่อหนึ่งกล่อง // กำหนดปริมาณกระสุนที่จะเพิ่มให้ผู้เล่นเมื่อเก็บกล่องนี้ (15 นัด)

    private void OnTriggerEnter(Collider other) // ฟังก์ชันทำงานอัตโนมัติเมื่อมีวัตถุอื่นเคลื่อนที่เข้ามาในพื้นที่ Trigger ของกล่องกระสุน
    { // เปิดขอบเขตการทำงานของฟังก์ชัน OnTriggerEnter
        // ตรวจว่าสิ่งที่เดินมาชนมี Tag เป็น Player หรือไม่ // คำอธิบายเพื่อเช็คความถูกต้องของเป้าหมายที่เดินมาสัมผัส
        if (other.CompareTag("Player")) // ตรวจสอบว่าวัตถุที่เข้ามาชนถูกตั้งค่า Tag เป็น "Player" ใช่หรือไม่
        { // เปิดขอบเขตเงื่อนไขเมื่อผู้เล่นเป็นคนชน
            PlayerAmmo ammo = other.GetComponent<PlayerAmmo>(); // ดึงคอมโพเนนต์ PlayerAmmo จากตัวผู้เล่นที่เข้ามาสัมผัส
            if (ammo != null) // ตรวจสอบว่าพบสคริปต์ PlayerAmmo บนตัวผู้เล่นจริงหรือไม่
            { // เปิดขอบเขตเงื่อนไขเมื่อพบสคริปต์ระบบกระสุน
                ammo.AddAmmo(ammoAmount); // เรียกฟังก์ชันเพิ่มกระสุนเข้าไปยังตัวผู้เล่นตามจำนวนที่กำหนดไว้
                Destroy(gameObject); // เก็บแล้วกล่องหายไปจากฉาก // ลบและทำลายวัตถุกล่องกระสุนนี้ออกจากฉากทันที
            } // ปิดขอบเขตเงื่อนไขเมื่อพบสคริปต์ระบบกระสุน
        } // ปิดขอบเขตเงื่อนไขเมื่อผู้เล่นเป็นคนชน
    } // ปิดขอบเขตการทำงานของฟังก์ชัน OnTriggerEnter
} // ปิดขอบเขตของคลาส AmmoBoxPickup