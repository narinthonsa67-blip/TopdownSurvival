using UnityEngine; // เรียกใช้งานไลบรารีพื้นฐานของ Unity เพื่อใช้งานฟังก์ชันและคอมโพเนนต์ทั่วไป
using TMPro; // เรียกใช้งานไลบรารี TextMeshPro สำหรับควบคุมและแสดงผลข้อความบน UI
public class PlayerAmmo : MonoBehaviour // ประกาศคลาสชื่อ PlayerAmmo สืบทอดจาก MonoBehaviour เพื่อใช้จัดการระบบกระสุน
{ // เปิดขอบเขตการทำงานของคลาส PlayerAmmo
    [Header("Ammo Settings")] // แสดงหัวข้อหมวดหมู่ "Ammo Settings" บนหน้าต่าง Inspector ใน Unity
    public int currentAmmo = 20; // จำนวนกระสุนเริ่มต้นที่มีอยู่ ณ ปัจจุบัน (เริ่มที่ 20 นัด)
    public int maxAmmo = 67; // จำนวนกระสุนสูงสุดที่ผู้เล่นสามารถเก็บพกติดตัวได้ (สูงสุด 67 นัด)

    [Header("UI")] // แสดงหัวข้อหมวดหมู่ "UI" บนหน้าต่าง Inspector ใน Unity
    public TextMeshProUGUI ammoText; // ตัวแปรสำหรับเชื่อมต่อกับกล่องข้อความ UI บนหน้าจอ เพื่อโชว์จำนวนกระสุน

    private void Start() // ฟังก์ชันที่ทำงานอัตโนมัติ 1 ครั้งเมื่อเริ่มเกม
    { // เปิดขอบเขตการทำงานของฟังก์ชัน Start
        UpdateAmmoUI(); // สั่งให้อัปเดตตัวเลขกระสุนขึ้นบนหน้าจอ UI ทันทีตอนเริ่มเกม
    } // ปิดขอบเขตการทำงานของฟังก์ชัน Start

    public bool CanShoot() // ฟังก์ชันสำหรับเช็คว่าผู้เล่นสามารถยิงปืนได้หรือไม่ (ส่งค่ากลับเป็น จริง/เท็จ)
    { // เปิดขอบเขตการทำงานของฟังก์ชัน CanShoot
        return currentAmmo > 0; // ส่งค่ากลับเป็นจริงถ้ายังมีกระสุนมากกว่า 0 (ยิงได้) ถ้าเป็น 0 จะส่งค่าเท็จ (ยิงไม่ได้)
    } // ปิดขอบเขตการทำงานของฟังก์ชัน CanShoot

    public void ConsumeAmmo() // ฟังก์ชันสำหรับหักลบกระสุนออกเมื่อผู้เล่นกดยิง
    { // เปิดขอบเขตการทำงานของฟังก์ชัน ConsumeAmmo
        if (currentAmmo > 0) // ตรวจสอบว่ายังมีกระสุนเหลืออยู่มากกว่า 0 นัดหรือไม่
        { // เปิดขอบเขตเงื่อนไขเมื่อมีกระสุนเหลือ
            currentAmmo--; // หักลดจำนวนกระสุนปัจจุบันลง 1 นัด
            UpdateAmmoUI(); // อัปเดตตัวเลขกระสุนที่ลดลงแล้วขึ้นบนหน้าจอ UI ทันที
        } // ปิดขอบเขตเงื่อนไขเมื่อมีกระสุนเหลือ
    } // ปิดขอบเขตการทำงานของฟังก์ชัน ConsumeAmmo

    public void AddAmmo(int amount) // ฟังก์ชันสำหรับเพิ่มกระสุนเมื่อเก็บกล่องกระสุนได้ (รับค่าจำนวนกระสุนที่จะเพิ่มเข้ามา)
    { // เปิดขอบเขตการทำงานของฟังก์ชัน AddAmmo
        currentAmmo = Mathf.Clamp(currentAmmo + amount, 0, maxAmmo); // บวกกระสุนเพิ่มเข้าไป พร้อมล็อกค่าไม่ให้เกินกระสุนสูงสุด (maxAmmo) และไม่ต่ำกว่า 0
        UpdateAmmoUI(); // อัปเดตตัวเลขกระสุนที่เพิ่มขึ้นแล้วขึ้นบนหน้าจอ UI ทันที
    } // ปิดขอบเขตการทำงานของฟังก์ชัน AddAmmo

    private void UpdateAmmoUI() // ฟังก์ชันสำหรับรีเฟรชข้อความตัวเลขกระสุนบนหน้าจอ UI
    { // เปิดขอบเขตการทำงานของฟังก์ชัน UpdateAmmoUI
        if (ammoText != null) // ตรวจสอบว่ามีการลากกล่องข้อความ UI มาใส่ในช่อง Inspector แล้วหรือยัง
        { // เปิดขอบเขตเงื่อนไขเมื่อมี UI เชื่อมต่ออยู่
            ammoText.text = $"Ammo: {currentAmmo} / {maxAmmo}"; // นำจำนวนกระสุนปัจจุบันและกระสุนสูงสุดมาแสดงผลเป็นข้อความ เช่น Ammo: 20 / 67
        } // ปิดขอบเขตเงื่อนไขเมื่อมี UI เชื่อมต่ออยู่
    } // ปิดขอบเขตการทำงานของฟังก์ชัน UpdateAmmoUI
} // ปิดขอบเขตของคลาส PlayerAmmo