using System.Collections;
using UnityEngine;
public class CameraShake : MonoBehaviour // นำเข้าไลบรารีระบบสำหรับการทำ Coroutine และคำสั่งพื้นฐานของ Unity พร้อมประกาศคลาสสั่นกล้อง
{ // เริ่มต้นบล็อกของคลาส CameraShake
    public static CameraShake Instance; // ตัวแปร Static รูปแบบ Singleton เพื่อให้สคริปต์อื่นเรียกสั่งสั่นกล้องได้ทันทีโดยไม่ต้องลากใส่

    private Vector3 initialPosition; // ตัวแปรสำหรับบันทึกตำแหน่งเริ่มต้นของกล้องไว้ เพื่อใช้ดึงกล้องกลับที่เดิมหลังสั่นเสร็จ

    private void Awake() // ฟังก์ชันทำงานก่อน Start ทันทีที่โหลดสคริปต์ขึ้นมา
    { // เริ่มต้นบล็อกฟังก์ชัน Awake
        if (Instance == null) // ตรวจสอบว่ายังไม่เคยมีระบบ CameraShake นี้ถูกสร้างขึ้นมาในฉากใช่ไหม
        { // เริ่มเงื่อนไขกรณีเป็นตัวแรก
            Instance = this; // กำหนดให้ตัวนี้เป็นตัวหลักของระบบ Singleton
        } // สิ้นสุดเงื่อนไขกรณีเป็นตัวแรก
        else // หากพบว่ามี CameraShake ตัวอื่นอยู่ในฉากแล้ว
        { // เริ่มเงื่อนไขกรณีมีตัวซ้ำ
            Destroy(gameObject); // สั่งทำลายตัวเองทิ้งทันที เพื่อป้องกันไม่ให้มีระบบสั่นกล้องซ้ำซ้อน
        } // สิ้นสุดเงื่อนไขกรณีมีตัวซ้ำ
    } // สิ้นสุดบล็อกฟังก์ชัน Awake

    private void Start() // ฟังก์ชันทำงานครั้งแรกเมื่อเกมเริ่ม
    { // เริ่มต้นบล็อกฟังก์ชัน Start
        // บันทึกตำแหน่งกล้องเริ่มต้นไว้
        initialPosition = transform.localPosition; // จำพิกัดตำแหน่งเริ่มต้นเทียบกับวัตถุแม่ไว้ในตัวแปร initialPosition
    } // สิ้นสุดบล็อกฟังก์ชัน Start

    // ฟังก์ชันเรียกให้กล้องสั่น (ส่งระยะเวลา และความแรงมาได้)
    public void Shake(float duration = 0.15f, float magnitude = 0.2f) // ฟังก์ชันสาธารณะสำหรับเรียกสั่นกล้อง โดยกำหนดระยะเวลาและความแรงได้ (มีค่าเริ่มต้นให้)
    { // เริ่มต้นบล็อกฟังก์ชัน Shake
        StopAllCoroutines(); // สั่งหยุด Coroutine สั่นกล้องเดิมทั้งหมดที่กำลังทำงานอยู่ ป้องกันไม่ให้การสั่นตีกัน
        StartCoroutine(ShakeRoutine(duration, magnitude)); // เริ่มต้นเรียกใช้งานฟังก์ชันสั่นกล้องแบบนับเวลาถอยหลัง (ShakeRoutine)
    } // สิ้นสุดบล็อกฟังก์ชัน Shake

    private IEnumerator ShakeRoutine(float duration, float magnitude) // ฟังก์ชันแบบ Coroutine ที่คอยสุ่มขยับตำแหน่งกล้องต่อเนื่องจนหมดเวลา
    { // เริ่มต้นบล็อกฟังก์ชัน ShakeRoutine
        float elapsed = 0f; // ตัวแปรจับเวลาที่ผ่านไปตั้งแต่เริ่มสั่น (เริ่มต้นที่ 0 วินาที)

        while (elapsed < duration) // วนลูปทำงานตราบใดที่เวลายังสั่นไม่ครบตามที่กำหนดไว้
        { // เริ่มต้นบล็อกลูปการสั่น
            // สุ่มตำแหน่งเบี่ยงเบนในแกน X และ Z (สำหรับมุมมอง Top-down)
            float offsetX = Random.Range(-1f, 1f) * magnitude; // สุ่มระยะคลาดเคลื่อนในแกน X ระหว่าง -1 ถึง 1 แล้วคูณด้วยระดับความแรง
            float offsetZ = Random.Range(-1f, 1f) * magnitude; // สุ่มระยะคลาดเคลื่อนในแกน Z ระหว่าง -1 ถึง 1 แล้วคูณด้วยระดับความแรง

            transform.localPosition = new Vector3( // สั่งเปลี่ยนตำแหน่งของกล้องแบบ Local ไปยังพิกัดใหม่ที่สุ่มได้
                initialPosition.x + offsetX, // นำพิกัดเริ่มต้นแกน X มาบวกกับระยะสั่นที่สุ่มได้
                initialPosition.y, // รักษาระดับความสูงแกน Y ไว้เท่าเดิม ไม่ให้กล้องยุบหรือลอย
                initialPosition.z + offsetZ // นำพิกัดเริ่มต้นแกน Z มาบวกกับระยะสั่นที่สุ่มได้
            ); // สิ้นสุดการกำหนดตำแหน่งใหม่

            elapsed += Time.deltaTime; // บวกเวลาของแต่ละเฟรมที่ผ่านไปเข้ากับตัวแปร elapsed
            yield return null; // สั่งหยุดรอ 1 เฟรมก่อนจะวนกลับมาคำนวณตำแหน่งสั่นในเฟรมถัดไป
        } // สิ้นสุดบล็อกลูปการสั่น

        // เมื่อสั่นเสร็จให้คืนตำแหน่งเดิม
        transform.localPosition = initialPosition; // ย้ายตำแหน่งของกล้องกลับไปยังพิกัดเดิมก่อนเริ่มสั่นทันที
    } // สิ้นสุดบล็อกฟังก์ชัน ShakeRoutine
} // สิ้นสุดบล็อกของคลาส CameraShake